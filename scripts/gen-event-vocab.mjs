// Writes src/lib/event-vocab.mjs: the CLOSED list of values an analytics event may carry (runs before every build).
// Values come from the site's own data and code, never from visitors, so a name, phone number or message can't
// pass even if a future change passes the wrong thing to window.track():
//   services   live service ids (src/data/services.json)    offers  offer ids (src/data/offers.json)
//   placements every literal `placement` in src/ and public/chat/spa-chat.js, plus the few site.ts computes.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const services = JSON.parse(readFileSync(join(root, 'src/data/services.json'), 'utf8')).services
  .filter((s) => s.status === 'live').map((s) => s.id);
const offers = JSON.parse(readFileSync(join(root, 'src/data/offers.json'), 'utf8')).offers.map((o) => o.id);
const walk = (d) => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const files = [...walk(join(root, 'src')).filter((f) => /\.(astro|ts|mjs)$/.test(f) && !f.endsWith('event-vocab.mjs')), join(root, 'public/chat/spa-chat.js')];
const placements = new Set(['bar', 'header', 'page', 'chat']); // computed in site.ts (openUni, inferTrack)
for (const f of files) {
  for (const m of readFileSync(f, 'utf8').matchAll(/placement["']?\s*[:=]\s*["']([a-z0-9][a-z0-9-]{0,39})["']/g)) placements.add(m[1]);
}
const sorted = (a) => [...new Set(a)].sort();
const out = `// GENERATED by scripts/gen-event-vocab.mjs before every build. Do not edit by hand.
export const SERVICES = ${JSON.stringify(sorted(services))};
export const OFFERS = ${JSON.stringify(sorted(offers))};
export const PLACEMENTS = ${JSON.stringify(sorted(placements))};
`;
writeFileSync(join(root, 'src/lib/event-vocab.mjs'), out);
console.log(`event vocab: ${services.length} services, ${offers.length} offers, ${placements.size} placements`);
