// Public subset of the owner's facts file (review finding 12).
//
// The owner's full facts.json (Square-confirmed prices plus internal notes, open questions and staff names) lives
// OUTSIDE this public repo. This script copies only what the website already publishes into facts/facts.public.json:
// services, prices, durations, locations, this month's special, gift card amounts, published policies and hours.
// scripts/check-geo.mjs prices llms.txt and the JSON-LD against that public file.
//
//   node scripts/make-public-facts.mjs /path/to/owner/facts.json    regenerate facts/facts.public.json
//   node scripts/make-public-facts.mjs --check [/path/to/facts.json] check the committed file (part of npm test);
//                                                                    with the owner's file, also check it is current
//
// Never edit facts/facts.public.json by hand. Never commit the owner's full file (.gitignore blocks facts/facts.json).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const OUT = join(root, 'facts', 'facts.public.json');

/** Words that mark an internal note, an open question or a hand-off instruction (never published). */
const INTERNAL = /NOT ON SITE|ask (the )?owner|hand(ed)? off|hand-off|owner decides|\bTODO\b|\bunknown\b|open question|\bconfirm\b|internal/i;

/** Drop "(... ask owner)" asides, then every sentence that still carries an internal marker. */
function publicText(s) {
  if (typeof s !== 'string') return undefined;
  let t = s.replace(/\s*\([^()]*\)/g, (m) => (INTERNAL.test(m) ? '' : m));
  t = t.split(/(?<=[.!?])\s+/).filter((x) => x.trim() && !INTERNAL.test(x)).join(' ').trim();
  return t || undefined;
}
const pick = (o, keys) => Object.fromEntries(keys.filter((k) => o[k] !== undefined && o[k] !== null).map((k) => [k, o[k]]));
const clean = (o) => JSON.parse(JSON.stringify(o)); // drops undefined

/** Staff first names the owner's notes mention (e.g. from reviews). Used only to prove none reach the public file. */
function staffNames(full) {
  const team = String(full?.business?.team || '');
  const m = team.match(/Staff named[^:]*:\s*([^.]*)/i);
  if (!m) return [];
  return [...m[1].matchAll(/\b([A-Z][a-z]+)\b/g)].map((x) => x[1]).filter((n) => !['and', 'The'].includes(n));
}

export function publicFacts(full) {
  const SERVICE_KEYS = ['id', 'group', 'name', 'desc', 'desc_style', 'aliases', 'tag', 'bold'];
  const OPTION_KEYS = ['minutes', 'duration', 'duration_text', 'price', 'price_from', 'price_note', 'locations'];
  const services = (full.services || [])
    .filter((s) => Array.isArray(s.options) && s.options.length && s.on_booking_menu !== false)
    .map((s) => clean({ ...pick(s, SERVICE_KEYS), options: s.options.map((o) => pick(o, OPTION_KEYS)) }));
  const sp = full.special || {};
  const policies = full.policies || {};
  const hours = full.business?.hours || {};
  return clean({
    _read_me: 'PUBLIC subset of the owner\'s facts file: only what the website publishes. Generated by scripts/make-public-facts.mjs from the owner\'s file (kept outside this repo). Do not edit by hand.',
    special: { start: sp.start, end: sp.end, items: (sp.items || []).map((i) => pick(i, ['id', 'group', 'name', 'minutes', 'price', 'locations', 'aliases', 'copy'])) },
    locations: (full.locations || []).map((l) => pick(l, ['code', 'name', 'address', 'booking_url'])),
    services,
    gift_cards: pick(full.gift_cards || {}, ['url', 'amounts', 'custom_amount']),
    policies: {
      ...pick(policies, ['cancellation_notice_hours', 'cancellation_fee', 'card_on_file_to_book_online', 'specials_terms', 'special_redemption']),
      deposits: publicText(policies.deposits),
      health: publicText(policies.health),
      prep: publicText(policies.prep),
      facials: publicText(policies.facials),
    },
    hours: pick(hours, ['days', 'open', 'close']),
    business: pick(full.business || {}, ['name', 'summary', 'phone', 'email']),
  });
}

/** Shape and content rules for the committed public file. Returns a list of problems. */
export function problems(pub, full = null) {
  const out = [];
  const TOP = ['_read_me', 'special', 'locations', 'services', 'gift_cards', 'policies', 'hours', 'business'];
  for (const k of Object.keys(pub)) if (!TOP.includes(k)) out.push(`unexpected top-level key "${k}"`);
  for (const k of ['special', 'locations', 'services', 'policies']) if (!(k in pub)) out.push(`missing "${k}"`);
  const text = JSON.stringify(pub);
  const body = JSON.stringify({ ...pub, _read_me: undefined });
  const m = body.match(INTERNAL);
  if (m) out.push(`internal note or open question in the public file: "${body.slice(Math.max(0, m.index - 40), m.index + 40)}"`);
  for (const k of ['unknowns', 'rules', 'sources', 'packages', 'team', 'owner', 'rating_claim', 'chat_note', 'chat_extra', 'note', 'voice_details', 'chat_details', '_monthly_edit', 'menu_rechecked', 'location_notes', 'contact_extra', 'payments']) {
    if (new RegExp(`"${k}"\\s*:`).test(text)) out.push(`internal field "${k}" in the public file`);
  }
  for (const s of pub.services || []) {
    for (const o of s.options || []) {
      if (o.price != null && typeof o.price !== 'number') out.push(`${s.id}: price is not a number`);
      if (!Array.isArray(o.locations) || !o.locations.every((l) => ['SD', 'DM'].includes(l))) out.push(`${s.id}: bad locations`);
    }
  }
  if (full) {
    for (const n of staffNames(full)) if (new RegExp(`\\b${n}\\b`).test(body)) out.push(`staff name "${n}" in the public file`);
    const want = JSON.stringify(publicFacts(full), null, 2) + '\n';
    if (want !== readFileSync(OUT, 'utf8')) out.push('facts/facts.public.json is out of date: run node scripts/make-public-facts.mjs <owner facts.json>');
  }
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  const checkOnly = args[0] === '--check';
  const fullPath = checkOnly ? args[1] || process.env.FACTS_FULL : args[0];
  const full = fullPath ? JSON.parse(readFileSync(fullPath, 'utf8')) : null;
  if (!checkOnly) {
    if (!full) { console.error('usage: node scripts/make-public-facts.mjs /path/to/owner/facts.json'); process.exit(2); }
    const pub = publicFacts(full);
    writeFileSync(OUT, JSON.stringify(pub, null, 2) + '\n');
    console.log(`wrote facts/facts.public.json: ${pub.services.length} services, ${pub.special.items.length} special(s)`);
  }
  if (!existsSync(OUT)) { console.error('✗ facts/facts.public.json missing'); process.exit(1); }
  if (existsSync(join(root, 'facts', 'facts.json'))) console.log('! facts/facts.json (the owner\'s full file) is in the repo folder: .gitignore keeps it out of commits; keep it outside the repo');
  const bad = problems(JSON.parse(readFileSync(OUT, 'utf8')), full);
  if (bad.length) { for (const b of bad) console.log(`✗ ${b}`); process.exit(1); }
  console.log(`✓ public facts: facts/facts.public.json holds only published facts${full ? ' and matches the owner\'s file' : ''}`);
}
